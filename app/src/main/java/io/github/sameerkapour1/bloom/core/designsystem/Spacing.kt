package io.github.sameerkapour1.bloom.core.designsystem

import androidx.compose.ui.unit.dp

/**
 * Spacing scale from plan.md §7. Screens use these instead of ad-hoc dp values.
 */
object BloomSpacing {
    /** 4 dp — micro spacing between tightly related elements. */
    val xs = 4.dp

    /** 8 dp — compact spacing inside a component. */
    val sm = 8.dp

    /** 12 dp — standard internal spacing. */
    val md = 12.dp

    /** 16 dp — base screen padding. */
    val base = 16.dp

    /** 24 dp — gap between sections. */
    val lg = 24.dp

    /** 32 dp — major section break. */
    val xl = 32.dp
}
